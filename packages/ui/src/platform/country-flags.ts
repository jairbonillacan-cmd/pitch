const VALID_ISO2 = new Set<string>(Object.values(COUNTRY_SLUG_TO_ICON_ID));

function slugifyCountry(raw: string): string {
  return raw
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function buildFlag(code: string): CircularCountryFlag {
  return {
    code,
    src: `/icons/32/paises/${code}.webp`,
    srcSet: `/icons/32/paises/${code}.webp 1x, /icons/64/paises/${code}.webp 2x`,
  };
}

/**
 * Resuelve el icono circular de país a partir de un slug (`mexico`, `inglaterra`),
 * nombre (`México`, `Alemania`), ruta previa (`/brand/official/countries/mexico.png`)
 * o código de 2/3 letras (`MX`, `MEX`, `ENG`, `gb-eng`).
 */
export function resolveCircularCountryFlag(
  input?: string | null,
  fallbackCode?: string | null,
): CircularCountryFlag | null {
  for (const candidate of [input, fallbackCode]) {
    const trimmed = candidate?.trim();
    if (!trimmed) continue;

    // Si recibimos una ruta previa `/brand/official/countries/<slug>.png` o `/flags/<slug>.png`
    const fileMatch = trimmed.match(/\/([a-z0-9-]+)\.(?:png|webp|svg)$/i);
    if (fileMatch?.[1]) {
      const base = fileMatch[1].toLowerCase();
      if (VALID_ISO2.has(base)) return buildFlag(base);
      const mappedFromFile = COUNTRY_SLUG_TO_ICON_ID[base];
      if (mappedFromFile) return buildFlag(mappedFromFile);
    }

    const upper = trimmed.toUpperCase();
    if (upper.length === 3 && CODE3_TO_ICON_ID[upper]) {
      return buildFlag(CODE3_TO_ICON_ID[upper]!);
    }

    const slug = slugifyCountry(trimmed);
    if (!slug) continue;
    if (COUNTRY_SLUG_TO_ICON_ID[slug]) {
      return buildFlag(COUNTRY_SLUG_TO_ICON_ID[slug]!);
    }
    if (VALID_ISO2.has(slug)) {
      return buildFlag(slug);
    }
  }
  return null;
}
